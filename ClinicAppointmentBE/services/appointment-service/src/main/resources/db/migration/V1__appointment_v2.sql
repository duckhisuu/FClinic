-- Fresh v2 baseline. Existing v1 Long patient references require an owned migration;
-- do not enable baseline-on-migrate or run a v1 writer on this schema.
CREATE TABLE appointments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id BETWEEN 1 AND 9007199254740991),
 booking_code varchar(40) NOT NULL UNIQUE,patient_id uuid NOT NULL,patient_name varchar(255) NOT NULL,
 patient_phone varchar(16) NOT NULL CHECK(patient_phone ~ '^\+[1-9][0-9]{7,14}$'),
 doctor_id bigint NOT NULL CHECK(doctor_id BETWEEN 1 AND 9007199254740991),doctor_name varchar(255) NOT NULL,doctor_specialty varchar(255) NOT NULL,
 slot_id bigint NOT NULL CHECK(slot_id BETWEEN 1 AND 9007199254740991),appointment_date date NOT NULL,start_time time NOT NULL,end_time time NOT NULL,
 reason_for_visit text,consultation_fee numeric NOT NULL CHECK(consultation_fee>=0 AND consultation_fee<'Infinity'::numeric),
 status varchar(20) NOT NULL CHECK(status IN('CONFIRMED','CANCELLED','COMPLETED','NO_SHOW')),
 version bigint NOT NULL DEFAULT 0 CHECK(version BETWEEN 0 AND 9007199254740991),created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL,
 CHECK(EXTRACT(MINUTE FROM start_time)=0 AND EXTRACT(SECOND FROM start_time)=0),CHECK(end_time>start_time AND end_time-start_time=interval '1 hour')
);
CREATE UNIQUE INDEX uq_confirmed_doctor_hour ON appointments(doctor_id,appointment_date,start_time) WHERE status='CONFIRMED';
CREATE INDEX ix_appointment_patient_date ON appointments(patient_id,appointment_date DESC,id DESC);
CREATE INDEX ix_appointment_doctor_date ON appointments(doctor_id,appointment_date,id);
CREATE TABLE appointment_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,appointment_id bigint NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
 action varchar(20) NOT NULL CHECK(action IN('CREATED','CANCELLED','RESCHEDULED','COMPLETED','NO_SHOW')),
 old_date date,old_start_time time,new_date date NOT NULL,new_start_time time NOT NULL,change_reason varchar(500),
 actor_subject varchar(255) NOT NULL,changed_by varchar(20) NOT NULL CHECK(changed_by IN('PATIENT','STAFF','DOCTOR','ADMIN','SYSTEM')),
 entity_version bigint NOT NULL CHECK(entity_version>=0),created_at timestamptz NOT NULL,UNIQUE(appointment_id,entity_version)
);
CREATE INDEX ix_history_parent ON appointment_history(appointment_id,created_at,id);
CREATE TABLE operation_results (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,caller_subject varchar(255) NOT NULL,operation varchar(30) NOT NULL,
 idempotency_key uuid NOT NULL,request_hash varchar(64) NOT NULL,appointment_id bigint NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
 response_status integer NOT NULL CHECK(response_status IN(200,201)),response_body text NOT NULL CHECK(response_body::jsonb IS NOT NULL),created_at timestamptz NOT NULL,
 UNIQUE(caller_subject,operation,idempotency_key)
);
CREATE TABLE outbox_events (
 id uuid PRIMARY KEY,aggregate_id bigint NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,aggregate_version bigint NOT NULL CHECK(aggregate_version>=0),
 event_type varchar(40) NOT NULL CHECK(event_type IN('APPOINTMENT_CREATED','APPOINTMENT_CANCELLED','APPOINTMENT_RESCHEDULED','APPOINTMENT_REMINDER')),
 intent jsonb NOT NULL,payload text CHECK(payload IS NULL OR payload::jsonb IS NOT NULL),status varchar(30) NOT NULL CHECK(status IN('PENDING_ENRICHMENT','READY','PUBLISHED','SUPPRESSED')),
 attempt_count integer NOT NULL DEFAULT 0 CHECK(attempt_count>=0),next_attempt_at timestamptz,last_error_code varchar(100),
 claim_token uuid,claimed_until timestamptz,published_at timestamptz,created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL,
 CHECK(status NOT IN('READY','PUBLISHED') OR payload IS NOT NULL),
 CHECK(NOT(intent ?| ARRAY['reasonForVisit','reason','diagnosis','treatment','notes'])),
 CHECK(payload IS NULL OR NOT(payload::jsonb ?| ARRAY['reasonForVisit','reason','diagnosis','treatment','notes']))
);
CREATE INDEX ix_outbox_due ON outbox_events(status,next_attempt_at,claimed_until,created_at);
CREATE TABLE reminder_publications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,appointment_id bigint NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
 aggregate_version bigint NOT NULL,reminder_due_at timestamptz NOT NULL,event_id uuid NOT NULL UNIQUE REFERENCES outbox_events(id) ON DELETE RESTRICT,
 UNIQUE(appointment_id,aggregate_version,reminder_due_at)
);
